
import logging

import requests
from django.conf import settings

from django_otp_toolkit.backends.base import BaseSMSBackend
from django_otp_toolkit.exceptions import OTPDeliveryError

logger = logging.getLogger(__name__)

MELIPAYAMAK_SHARED_URL = (
    "https://console.melipayamak.com/api/send/shared/{api_key}"
)


class MelipayamakBackend(BaseSMSBackend):
    """
    SMS backend using Melipayamak Shared API.
    """

    def __init__(self):
        self.api_key = getattr(
            settings, "MELIPAYAMAK_API_KEY", ""
        )
        self.body_id = getattr(
            settings, "MELIPAYAMAK_BODY_ID", None
        )
        self.timeout = getattr(
            settings, "MELIPAYAMAK_TIMEOUT", 10
        )

        if not self.api_key:
            raise OTPDeliveryError(
                "Melipayamak API key is not configured."
            )

        if not self.body_id:
            raise OTPDeliveryError(
                "Melipayamak body ID is not configured."
            )

    def send(self, to: str, message: str) -> bool:
        """
        Send an SMS using Melipayamak Shared API.

        The OTP must be generated by Django.
        """

        url = MELIPAYAMAK_SHARED_URL.format(
            api_key=self.api_key
        )

        payload = {
            "to": to,
            "bodyId": self.body_id,
            "args": [message],
        }

        try:
            response = requests.post(
                url,
                json=payload,
                timeout=self.timeout,
            )
            response.raise_for_status()

            result = response.json()

        except requests.RequestException as exc:
            logger.exception("Melipayamak request failed.")
            raise OTPDeliveryError(
                "Failed to communicate with Melipayamak."
            ) from exc

        except ValueError as exc:
            logger.exception("Invalid Melipayamak response.")
            raise OTPDeliveryError(
                "Melipayamak returned an invalid response."
            ) from exc

        if not isinstance(result, dict):
            raise OTPDeliveryError(
                "Unexpected Melipayamak response format."
            )

        status = result.get("status")
        rec_id = result.get("recId")

        if status:
            raise OTPDeliveryError(
                f"Melipayamak delivery failed: {status}"
            )

        if not rec_id:
            raise OTPDeliveryError(
                "Melipayamak did not return a message ID."
            )

        return True